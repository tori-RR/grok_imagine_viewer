import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import vm from "node:vm";
const read = name => readFileSync(new URL("../" + name, import.meta.url), "utf8");
let captured, realCalls = 0;
const context = vm.createContext({Date, GivEnvironment: {create: options => { captured = options; return "controller"; }}});
vm.runInContext(read("tests/fixtures/environment-preview.js"), context);
let time = 0;
const fixture = context.GivEnvironmentPreview.simulation(() => time);
assert.equal((await fixture.health()).ffmpeg.ready, false);
assert.equal((await fixture.bridge.getEnvironmentStatus()).webview2.ready, false);
assert.equal((await fixture.bridge.getEnvironmentStatus()).simulation, true);
await assert.rejects(fixture.bridge.installEnvironmentComponent("arbitrary"));
assert.equal((await fixture.bridge.installEnvironmentComponent("ffmpeg")).phase, "running");
await assert.rejects(fixture.bridge.installEnvironmentComponent("webview2"), /unavailable/);
time = 900;
assert.equal((await fixture.health()).ffmpeg.ready, true);
assert.equal((await fixture.bridge.getEnvironmentStatus()).install.phase, "finished");
assert.equal((await fixture.bridge.getEnvironmentStatus()).webview2.ready, false);
await fixture.bridge.installEnvironmentComponent("webview2"); time = 1800;
assert.equal((await fixture.bridge.getEnvironmentStatus()).webview2.ready, true);
assert.equal((await context.GivEnvironmentPreview.simulation().health()).ffmpeg.ready, false, "restart resets the simulation");
assert.equal(context.GivEnvironment.create({api: async url => { realCalls++; return url; }, bridge: {getEnvironmentStatus() { throw Error("must not call real native health"); }, installEnvironmentComponent() { throw Error("must not launch a real installer"); }}}), "controller");
assert.equal((await captured.api("/api/environment")).ffmpeg.ready, false);
await captured.bridge.installEnvironmentComponent("ffmpeg");
assert.equal(realCalls, 0, "simulated environment paths never reach a real API");
assert.equal(await captured.api("/fixture-safe"), "/fixture-safe");
assert.equal(realCalls, 1);
const config = JSON.parse(read("src-tauri/tauri.environment-preview.conf.json"));
assert.notEqual(config.identifier, JSON.parse(read("src-tauri/tauri.conf.json")).identifier);
assert.match(config.identifier, /environment-preview$/);
const production = vm.createContext({setTimeout, clearTimeout});
vm.runInContext(read("static/environment.js"), production);
const view = production.GivEnvironment.view(await fixture.health(), await fixture.bridge.getEnvironmentStatus(), false, "");
assert.equal(view.visible, false, "all simulated components ready hides the panel");
console.log("ok  preview starts missing, serializes simulated installs, resets, isolates configuration and never calls real install/health APIs");
